        assertEquals(0, AndroidSystemTrustRootsV1(source(arrayOf(legacy, supported))).copyInto(destination, written) { false })
        assertEquals(10, written[0])
        val bytes = ByteArray(written[0]); destination.get(bytes)
        assertArrayEquals(byteArrayOf(1,0,1,0,0,0,3,0x30,0x30,0x30), bytes)
        assertNull(legacy.last)
        destination.clear()
        assertEquals(12, AndroidSystemTrustRootsV1(source(arrayOf(legacy))).copyInto(destination, written) { false })
        assertEquals(0, written[0])
        for(i in 0 until destination.capacity()) assertEquals(0, destination.get(i).toInt())
    }
