    @Test fun managerAmbiguityAndExactCapacityBoundaries() {
        val selections = listOf(
            emptyArray<TrustManager>(),
            arrayOf<TrustManager>(Manager(arrayOf(Certificate(1))), Manager(arrayOf(Certificate(1)))),
            arrayOf<TrustManager>(object : TrustManager {}),
        )
        for (managers in selections) {
            val roots = AndroidSystemTrustRootsV1(AndroidSystemTrustRootsSourceV1 {
                AndroidSystemTrustSelectionV1("AndroidNSSP", managers, "android.security.net.config.RootTrustManager")
            })
            val dst = ByteBuffer.allocateDirect(8); dst.put(0, 99)
            val written = intArrayOf(99)
            assertEquals(12, roots.copyInto(dst, written) { false })
            assertEquals(0, written[0]); for (i in 0 until 8) assertEquals(0, dst.get(i).toInt())
        }
        // 3-byte header + 64 length fields + 63*16384 + 16125 = 1048576.
        for ((last, expected) in listOf(16125 to 0, 16126 to 6)) {
            val certs = Array<X509Certificate>(64) { Certificate(if (it == 63) last else 16384) }
            val dst = ByteBuffer.allocateDirect(1048576); val written = intArrayOf(99)
            assertEquals(expected, AndroidSystemTrustRootsV1(source(certs)).copyInto(dst, written) { false })
            assertEquals(if (expected == 0) 1048576 else 0, written[0])
            if (expected != 0) for (i in 0 until dst.capacity()) assertEquals(0, dst.get(i).toInt())
        }
        val written = intArrayOf(99)
        assertEquals(0, AndroidSystemTrustRootsV1(source(Array(512) { Certificate(1) }))
            .copyInto(ByteBuffer.allocateDirect(2563), written) { false })
        assertEquals(2563, written[0])
        var sourceReads = 0
        val unavailable = AndroidSystemTrustRootsV1(AndroidSystemTrustRootsSourceV1 { sourceReads++; error("source") })
        val dst = ByteBuffer.allocateDirect(8)
        assertEquals(8, unavailable.copyInto(dst, written) { true }); assertEquals(0, sourceReads)
        assertEquals(12, unavailable.copyInto(dst, written) { false }); assertEquals(1, sourceReads)
        assertEquals(0, written[0]); for (i in 0 until 8) assertEquals(0, dst.get(i).toInt())
    }

    private class Certificate(private val size: Int, private val fail: Boolean = false, private val serial: BigInteger = BigInteger.ONE) : X509Certificate() {
        var last: ByteArray? = null
        override fun getEncoded(): ByteArray {
            check(!fail)
            return ByteArray(size) { 0x30 }.also { last = it }
        }
        override fun checkValidity() = Unit
        override fun checkValidity(date: Date) = Unit
        override fun getVersion() = 3
        override fun getSerialNumber(): BigInteger = serial
        override fun getIssuerDN(): Principal = Principal { "test" }
        override fun getSubjectDN(): Principal = Principal { "test" }
        override fun getNotBefore() = Date(0)
        override fun getNotAfter() = Date(1)
        override fun getTBSCertificate() = byteArrayOf()
        override fun getSignature() = byteArrayOf()
        override fun getSigAlgName() = "test"
        override fun getSigAlgOID() = "1.2.3"
        override fun getSigAlgParams(): ByteArray? = null
        override fun getIssuerUniqueID(): BooleanArray? = null
        override fun getSubjectUniqueID(): BooleanArray? = null
        override fun getKeyUsage(): BooleanArray? = null
        override fun getBasicConstraints() = -1
        override fun verify(key: PublicKey) = Unit
        override fun verify(key: PublicKey, provider: String) = Unit
        override fun getPublicKey(): PublicKey? = null
        override fun hasUnsupportedCriticalExtension() = false
        override fun getCriticalExtensionOIDs(): Set<String>? = null
        override fun getNonCriticalExtensionOIDs(): Set<String>? = null
        override fun getExtensionValue(oid: String): ByteArray? = null
        override fun toString() = "TestCertificate"
    }
    private class Manager(private val issuers: Array<X509Certificate>) : X509TrustManager {
        override fun getAcceptedIssuers() = issuers
        override fun checkClientTrusted(chain: Array<X509Certificate>, authType: String) = Unit
        override fun checkServerTrusted(chain: Array<X509Certificate>, authType: String) = Unit
    }
    private fun source(certificates: Array<X509Certificate>, provider: String = "AndroidNSSP", name: String = "android.security.net.config.RootTrustManager") =
        AndroidSystemTrustRootsSourceV1 { AndroidSystemTrustSelectionV1(provider, arrayOf<TrustManager>(Manager(certificates)), name) }

    @Test fun exactFramingUsesOneTemporaryAndWipesIt() {
        val first = Certificate(2); val second = Certificate(3)
        val roots = AndroidSystemTrustRootsV1(source(arrayOf(first, second)))
        val destination = ByteBuffer.allocateDirect(16)
        val written = intArrayOf(99)
        assertEquals(0, roots.copyInto(destination, written) { false })
        assertEquals(16, written[0])
        val bytes = ByteArray(16); destination.get(bytes)
        assertArrayEquals(byteArrayOf(1,0,2,0,0,0,2,0x30,0x30,0,0,0,3,0x30,0x30,0x30), bytes)
        assertTrue(first.last!!.all { it == 0.toByte() }); assertTrue(second.last!!.all { it == 0.toByte() })
    }

    @Test fun limitsAmbiguityEncodingAndCancellationWipePartialOutput() {
        val cases = listOf(
            source(emptyArray()) to 12,
            source(Array(513) { Certificate(1) }) to 6,
            source(arrayOf(Certificate(16385))) to 6,
            source(arrayOf(Certificate(0))) to 12,
            source(arrayOf(Certificate(1)), provider = "other") to 12,
            source(arrayOf(Certificate(1)), name = "other") to 12,
            source(arrayOf(Certificate(2), Certificate(1, true))) to 12,
            source(Array(64) { Certificate(16384) }) to 6,
        )
        for ((source, expected) in cases) {
            val dst = ByteBuffer.allocateDirect(1048576)
            for (i in 0 until dst.capacity()) dst.put(i, 0x6a)
            val written = intArrayOf(7)
            assertEquals(expected, AndroidSystemTrustRootsV1(source).copyInto(dst, written) { false })
            assertEquals(0, written[0])
            for (i in 0 until dst.capacity()) assertEquals(0, dst.get(i).toInt())
        }
        val roots = AndroidSystemTrustRootsV1(source(arrayOf(Certificate(2), Certificate(3))))
        val dst = ByteBuffer.allocateDirect(16); val written = intArrayOf(7)
        var checks = 0
        assertEquals(8, roots.copyInto(dst, written) { ++checks > 2 })
        assertEquals(0, written[0]); for (i in 0 until 16) assertEquals(0, dst.get(i).toInt())
    }

    @Test fun malformedViewStillWipesWholeBorrowedCapacityWithoutThrowing() {
        val roots = AndroidSystemTrustRootsV1(source(arrayOf(Certificate(2))))
        val dst = ByteBuffer.allocateDirect(16)
        for (i in 0 until 16) dst.put(i, 0x5a)
        dst.limit(4)
        val written = intArrayOf(9)
        assertEquals(1, roots.copyInto(dst, written) { false })
        assertEquals(0, written[0])
        assertEquals(4, dst.limit())
        val full = dst.duplicate().apply { clear() }
        for (i in 0 until 16) assertEquals(0, full.get(i).toInt())
    }
