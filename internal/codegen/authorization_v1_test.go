func generatedTreeDigestV1(t *testing.T, root string) string {
	t.Helper()
	var paths []string
	err := filepath.Walk(root, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		if !info.IsDir() {
			paths = append(paths, path)
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	sort.Strings(paths)
	h := sha256.New()
	for _, path := range paths {
		rel, err := filepath.Rel(root, path)
		if err != nil {
			t.Fatal(err)
		}
		independentLPV1BufferV1(h, []byte(filepath.ToSlash(rel)))
		b, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		independentLPV1BufferV1(h, b)
	}
	return hex.EncodeToString(h.Sum(nil))
}

type byteWriterV1 interface{ Write([]byte) (int, error) }

func independentLPV1BufferV1(out byteWriterV1, value []byte) {
	var n [4]byte
	binary.BigEndian.PutUint32(n[:], uint32(len(value)))
	_, _ = out.Write(n[:])
	_, _ = out.Write(value)
}

