func TestAuthorizationCatalogCanonicalPermutationAndCloneIsolation(t *testing.T) {
	entry := independentEntryV1(t, 50)
	// Give each role distinct provenance while retaining valid, independently encoded pins.
	relayHash := sha256.Sum256([]byte("independent-relay-profile-50"))
	entry.Relay.ProfileHash = hex.EncodeToString(relayHash[:])
	ordered := catalogRawV1(t, AuthorizationCatalogScopeExplicitV1, []entryWireV1{entry})
	permuted := []byte(`{"entries":` + string(mustJSONV1(t, []entryWireV1{entry})) + `,"scope":"explicit_v1","version":"profile-authorization-catalog-v1"}`)
	a, err := ParseAuthorizationCatalogV1(ordered)
	if err != nil {
		t.Fatal(err)
	}
	b, err := ParseAuthorizationCatalogV1(permuted)
	if err != nil {
		t.Fatal(err)
	}
	ac, _ := a.canonical()
	bc, _ := b.canonical()
	if !bytes.Equal(ac, bc) || a.digest != b.digest {
		t.Fatal("member permutation changed canonical catalog")
	}
	if a.client.entries[0].pin == a.relay.entries[0].pin {
		t.Fatal("asymmetric role pins collapsed")
	}
	// Parsed state owns its data: changing caller bytes and a copied role slice cannot silently validate.
	before := a.digest
	for i := range ordered {
		ordered[i] ^= 0xff
	}
	if a.digest != before || a.validate() != nil {
		t.Fatal("caller mutation altered parsed catalog")
	}
	copyCatalog := a
	copyCatalog.client.entries = append([]authorizationEntryV1(nil), a.client.entries...)
	copyCatalog.relay.entries = append([]authorizationEntryV1(nil), a.relay.entries...)
	copyCatalog.client.entries[0].pin.ProfileHash[0] ^= 1
	if a.validate() != nil || copyCatalog.validate() == nil {
		t.Fatal("deep-clone isolation not enforced")
	}
}

